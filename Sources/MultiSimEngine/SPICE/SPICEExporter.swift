import Foundation

/// Generates standard SPICE 3 / ngspice / LTspice compatible netlists (.cir) from the circuit.
public final class SPICEExporter {
    public static func export(circuit: Circuit, title: String = "MULTIMACSIM.v1 Schematic") -> String {
        let (pinToNode, _) = circuit.resolveNodes()

        var lines: [String] = []
        lines.append("* \(title)")
        lines.append("* Generated by MULTIMACSIM.v1 — B.Tech Year 1 Electrical Edition")
        lines.append("* ----------------------------------------------------")
        lines.append("")

        var modelsToInclude = Set<String>()

        for comp in circuit.components {
            let pins = comp.pins
            let n = pins.map { pin in
                let nodeIdx = pinToNode[pin.id] ?? 0
                return nodeIdx == 0 ? "0" : "N\(nodeIdx)"
            }

            let name = comp.designator.isEmpty ? "PART" : comp.designator

            switch comp.kind {
            case .ground:
                // Ground is node 0 implicitly
                break

            case .resistor:
                let n1 = n.count > 0 ? n[0] : "0"
                let n2 = n.count > 1 ? n[1] : "0"
                lines.append("\(name) \(n1) \(n2) \(formatValue(comp.value))")

            case .capacitor:
                let n1 = n.count > 0 ? n[0] : "0"
                let n2 = n.count > 1 ? n[1] : "0"
                lines.append("\(name) \(n1) \(n2) \(formatValue(comp.value))")

            case .inductor:
                let n1 = n.count > 0 ? n[0] : "0"
                let n2 = n.count > 1 ? n[1] : "0"
                lines.append("\(name) \(n1) \(n2) \(formatValue(comp.value))")

            case .dcVoltageSource:
                let nPlus = n.count > 0 ? n[0] : "0"
                let nMinus = n.count > 1 ? n[1] : "0"
                lines.append("\(name) \(nPlus) \(nMinus) DC \(comp.value)")

            case .acVoltageSource:
                let nPlus = n.count > 0 ? n[0] : "0"
                let nMinus = n.count > 1 ? n[1] : "0"
                let freq = comp.secondaryValue > 0 ? comp.secondaryValue : 60.0
                lines.append("\(name) \(nPlus) \(nMinus) SIN(0 \(comp.value) \(freq))")

            case .clockSource:
                let nPlus = n.count > 0 ? n[0] : "0"
                let nMinus = n.count > 1 ? n[1] : "0"
                let freq = comp.secondaryValue > 0 ? comp.secondaryValue : 1000.0
                let period = 1.0 / freq
                lines.append("\(name) \(nPlus) \(nMinus) PULSE(0 \(comp.value) 0 1n 1n \(period*0.5) \(period))")

            case .dcCurrentSource:
                let nOut = n.count > 0 ? n[0] : "0"
                let nIn = n.count > 1 ? n[1] : "0"
                lines.append("\(name) \(nIn) \(nOut) DC \(comp.value)")

            case .diode:
                let nA = n.count > 0 ? n[0] : "0"
                let nK = n.count > 1 ? n[1] : "0"
                lines.append("\(name) \(nA) \(nK) D1N4148")
                modelsToInclude.insert(".model D1N4148 D (Is=1e-14 Rs=0.1 N=1)")

            case .led:
                let nA = n.count > 0 ? n[0] : "0"
                let nK = n.count > 1 ? n[1] : "0"
                lines.append("\(name) \(nA) \(nK) DLED")
                modelsToInclude.insert(".model DLED D (Is=1e-18 N=2)")

            case .zenerDiode:
                let nA = n.count > 0 ? n[0] : "0"
                let nK = n.count > 1 ? n[1] : "0"
                let vz = comp.secondaryValue > 0 ? comp.secondaryValue : 5.1
                lines.append("\(name) \(nA) \(nK) DZENER")
                modelsToInclude.insert(".model DZENER D (Is=1e-14 Bv=\(vz))")

            case .bjtNPN:
                let nB = n.count > 0 ? n[0] : "0"
                let nC = n.count > 1 ? n[1] : "0"
                let nE = n.count > 2 ? n[2] : "0"
                let beta = comp.secondaryValue > 0 ? comp.secondaryValue : 100.0
                lines.append("\(name) \(nC) \(nB) \(nE) Q2N2222")
                modelsToInclude.insert(".model Q2N2222 NPN (Bf=\(beta) Is=1e-14)")

            case .bjtPNP:
                let nB = n.count > 0 ? n[0] : "0"
                let nC = n.count > 1 ? n[1] : "0"
                let nE = n.count > 2 ? n[2] : "0"
                let beta = comp.secondaryValue > 0 ? comp.secondaryValue : 100.0
                lines.append("\(name) \(nC) \(nB) \(nE) Q2N2907")
                modelsToInclude.insert(".model Q2N2907 PNP (Bf=\(beta) Is=1e-14)")

            case .switchSPST:
                let n1 = n.count > 0 ? n[0] : "0"
                let n2 = n.count > 1 ? n[1] : "0"
                let r = comp.stateBool ? 1e-4 : 1e9
                lines.append("\(name) \(n1) \(n2) \(r)")

            case .potentiometer:
                let n1 = n.count > 0 ? n[0] : "0"
                let n2 = n.count > 1 ? n[1] : "0"
                let ratio = min(max(comp.secondaryValue > 0 ? comp.secondaryValue : 0.5, 0.001), 0.999)
                lines.append("\(name) \(n1) \(n2) \(formatValue(comp.value * ratio))")

            case .vcvs:
                let nOutP = n.count > 0 ? n[0] : "0"
                let nOutM = n.count > 1 ? n[1] : "0"
                let nCtrlP = n.count > 2 ? n[2] : "0"
                let nCtrlM = n.count > 3 ? n[3] : "0"
                lines.append("\(name) \(nOutP) \(nOutM) \(nCtrlP) \(nCtrlM) \(comp.value)")

            case .vccs:
                let nOutP = n.count > 0 ? n[0] : "0"
                let nOutM = n.count > 1 ? n[1] : "0"
                let nCtrlP = n.count > 2 ? n[2] : "0"
                let nCtrlM = n.count > 3 ? n[3] : "0"
                lines.append("\(name) \(nOutP) \(nOutM) \(nCtrlP) \(nCtrlM) \(comp.value)")

            default:
                break
            }
        }

        if !modelsToInclude.isEmpty {
            lines.append("")
            lines.append("* Models")
            for model in modelsToInclude.sorted() {
                lines.append(model)
            }
        }

        lines.append("")
        lines.append("* Analysis Directives")
        lines.append(".tran 10u 10m")
        lines.append(".end")

        return lines.joined(separator: "\n")
    }

    private static func formatValue(_ val: Double) -> String {
        if val >= 1e6 {
            return String(format: "%.3gMEG", val / 1e6)
        } else if val >= 1e3 {
            return String(format: "%.3gk", val / 1e3)
        } else if val >= 1.0 {
            return String(format: "%.3g", val)
        } else if val >= 1e-3 {
            return String(format: "%.3gm", val * 1e3)
        } else if val >= 1e-6 {
            return String(format: "%.3gu", val * 1e6)
        } else if val >= 1e-9 {
            return String(format: "%.3gn", val * 1e9)
        } else if val >= 1e-12 {
            return String(format: "%.3gp", val * 1e12)
        } else {
            return "\(val)"
        }
    }
}
