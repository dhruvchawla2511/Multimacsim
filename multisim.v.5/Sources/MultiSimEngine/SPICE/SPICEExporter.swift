import Foundation

/// Generates standard SPICE 3 / ngspice / LTspice compatible netlists (.cir) from the circuit.
public final class SPICEExporter {
    public static func export(circuit: Circuit, title: String = "MULTIMACSIM.v1 Schematic") -> String {
        let (pinToNode, _) = circuit.resolveNodes()

        var lines: [String] = []
        lines.append("* \(title)")
        lines.append("* Generated by MULTIMACSIM.v1 — B.Tech Year 1 Electrical Edition")
        lines.append("* ----------------------------------------------------")
        lines.append("")

        var modelsToInclude = Set<String>()

        for comp in circuit.components {
            let pins = comp.pins
            let n = pins.map { pin in
                let nodeIdx = pinToNode[pin.id] ?? 0
                return nodeIdx == 0 ? "0" : "N\(nodeIdx)"
            }

            let name = comp.designator.isEmpty ? "PART" : comp.designator

            func node(_ index: Int) -> String { index < n.count ? n[index] : "0" }

            switch comp.kind {
            case .ground:
                // Ground is node 0 implicitly
                break

            case .resistor:
                let n1 = n.count > 0 ? n[0] : "0"
                let n2 = n.count > 1 ? n[1] : "0"
                lines.append("\(name) \(n1) \(n2) \(formatValue(comp.value))")

            case .capacitor:
                let n1 = n.count > 0 ? n[0] : "0"
                let n2 = n.count > 1 ? n[1] : "0"
                lines.append("\(name) \(n1) \(n2) \(formatValue(comp.value))")

            case .inductor:
                let n1 = n.count > 0 ? n[0] : "0"
                let n2 = n.count > 1 ? n[1] : "0"
                lines.append("\(name) \(n1) \(n2) \(formatValue(comp.value))")

            case .dcVoltageSource:
                let nPlus = n.count > 0 ? n[0] : "0"
                let nMinus = n.count > 1 ? n[1] : "0"
                lines.append("\(name) \(nPlus) \(nMinus) DC \(comp.value)")

            case .acVoltageSource:
                let nPlus = n.count > 0 ? n[0] : "0"
                let nMinus = n.count > 1 ? n[1] : "0"
                let freq = comp.secondaryValue > 0 ? comp.secondaryValue : 60.0
                lines.append("\(name) \(nPlus) \(nMinus) SIN(0 \(comp.value) \(freq))")

            case .clockSource:
                let nPlus = n.count > 0 ? n[0] : "0"
                let nMinus = n.count > 1 ? n[1] : "0"
                let freq = comp.secondaryValue > 0 ? comp.secondaryValue : 1000.0
                let period = 1.0 / freq
                lines.append("\(name) \(nPlus) \(nMinus) PULSE(0 \(comp.value) 0 1n 1n \(period*0.5) \(period))")

            case .dcCurrentSource:
                let nOut = n.count > 0 ? n[0] : "0"
                let nIn = n.count > 1 ? n[1] : "0"
                lines.append("\(name) \(nIn) \(nOut) DC \(comp.value)")

            case .diode:
                let nA = n.count > 0 ? n[0] : "0"
                let nK = n.count > 1 ? n[1] : "0"
                lines.append("\(name) \(nA) \(nK) D1N4148")
                modelsToInclude.insert(".model D1N4148 D (Is=1e-14 Rs=0.1 N=1)")

            case .led:
                let nA = n.count > 0 ? n[0] : "0"
                let nK = n.count > 1 ? n[1] : "0"
                lines.append("\(name) \(nA) \(nK) DLED")
                modelsToInclude.insert(".model DLED D (Is=1e-18 N=2)")

            case .zenerDiode:
                let nA = n.count > 0 ? n[0] : "0"
                let nK = n.count > 1 ? n[1] : "0"
                let vz = comp.secondaryValue > 0 ? comp.secondaryValue : 5.1
                lines.append("\(name) \(nA) \(nK) DZENER")
                modelsToInclude.insert(".model DZENER D (Is=1e-14 Bv=\(vz))")

            case .bjtNPN:
                let nB = n.count > 0 ? n[0] : "0"
                let nC = n.count > 1 ? n[1] : "0"
                let nE = n.count > 2 ? n[2] : "0"
                let beta = comp.secondaryValue > 0 ? comp.secondaryValue : 100.0
                lines.append("\(name) \(nC) \(nB) \(nE) Q2N2222")
                modelsToInclude.insert(".model Q2N2222 NPN (Bf=\(beta) Is=1e-14)")

            case .bjtPNP:
                let nB = n.count > 0 ? n[0] : "0"
                let nC = n.count > 1 ? n[1] : "0"
                let nE = n.count > 2 ? n[2] : "0"
                let beta = comp.secondaryValue > 0 ? comp.secondaryValue : 100.0
                lines.append("\(name) \(nC) \(nB) \(nE) Q2N2907")
                modelsToInclude.insert(".model Q2N2907 PNP (Bf=\(beta) Is=1e-14)")

            case .switchSPST:
                let n1 = n.count > 0 ? n[0] : "0"
                let n2 = n.count > 1 ? n[1] : "0"
                let r = comp.stateBool ? 1e-4 : 1e9
                lines.append("\(name) \(n1) \(n2) \(r)")

            case .potentiometer:
                let ratio = min(max(comp.secondaryValue > 0 ? comp.secondaryValue : 0.5, 0.001), 0.999)
                if pins.count >= 3 {
                    // A real 3-terminal divider: track split at the wiper.
                    lines.append("\(name)A \(node(0)) \(node(2)) \(formatValue(comp.value * ratio))")
                    lines.append("\(name)B \(node(2)) \(node(1)) \(formatValue(comp.value * (1 - ratio)))")
                } else {
                    lines.append("\(name) \(node(0)) \(node(1)) \(formatValue(comp.value * ratio))")
                }

            case .rheostat:
                let ratio = min(max(comp.secondaryValue > 0 ? comp.secondaryValue : 0.5, 0.001), 0.999)
                lines.append("\(name) \(node(0)) \(node(1)) \(formatValue(comp.value * ratio))")

            case .lamp:
                lines.append("\(name) \(node(0)) \(node(1)) \(formatValue(comp.value > 0 ? comp.value : 10))")

            case .fuse:
                let r = comp.stateBool ? (comp.value > 0 ? comp.value : 0.05) : 1e9
                lines.append("\(name) \(node(0)) \(node(1)) \(formatValue(r))")
                if comp.stateBool, comp.secondaryValue > 0 {
                    lines.append("* \(name) fuse rated \(comp.secondaryValue)A")
                }

            case .thermistor:
                // NTC: R = R25 * exp(B * (1/T - 1/298.15))
                let tempC = comp.secondaryValue > 0 ? comp.secondaryValue : 25
                let r25 = comp.value > 0 ? comp.value : 10_000
                let kelvin = tempC + 273.15
                let resistance = r25 * exp(3950.0 * (1.0 / kelvin - 1.0 / 298.15))
                lines.append("\(name) \(node(0)) \(node(1)) \(formatValue(resistance))")
                lines.append("* NTC thermistor at \(tempC) C")

            case .photoResistor:
                let lux = comp.secondaryValue > 0 ? comp.secondaryValue : 100
                let r10 = comp.value > 0 ? comp.value : 5_000
                lines.append("\(name) \(node(0)) \(node(1)) \(formatValue(r10 * pow(lux / 10.0, -0.7)))")

            case .electrolyticCapacitor, .trimmerCapacitor:
                lines.append("\(name) \(node(0)) \(node(1)) \(formatValue(comp.value))")

            case .ammeter:
                lines.append("\(name) \(node(0)) \(node(1)) \(formatValue(comp.value > 0 ? comp.value : 1e-3))")
                lines.append("* \(name) ammeter burden resistance - read branch current with a PRINT/SAVE statement")

            case .voltmeter:
                lines.append("\(name) \(node(0)) \(node(1)) \(formatValue(comp.value > 0 ? comp.value : 1e7))")

            case .galvanometer:
                lines.append("\(name) \(node(0)) \(node(1)) \(formatValue(comp.value > 0 ? comp.value : 100))")

            case .multimeter:
                let resistance: Double
                let note: String
                switch MeterMode(rawValue: comp.modeIndex) ?? .voltage {
                case .voltage:
                    resistance = comp.value > 0 ? comp.value : 1e7
                    note = "voltage mode (parallel)"
                case .current:
                    resistance = comp.value > 0 ? max(comp.value, 1e-6) : 1e-3
                    note = "current mode (series)"
                case .resistance:
                    resistance = 1e9
                    note = "ohm mode - measure V/I across the unknown"
                }
                lines.append("\(name) \(node(0)) \(node(1)) \(formatValue(resistance))")
                lines.append("* \(name) multimeter in \(note)")

            case .ohmmeter:
                let test = comp.value > 0 ? comp.value : 1e-3
                lines.append("\(name) \(node(1)) \(node(0)) DC \(formatValue(test))")
                lines.append("* \(name) ohmmeter test current; R = V(node)/I(source)")

            case .wattmeter:
                lines.append("\(name)CC \(node(0)) \(node(1)) \(formatValue(comp.value > 0 ? comp.value : 0.05))")
                lines.append("\(name)PC \(node(2)) \(node(3)) \(formatValue(comp.secondaryValue > 0 ? comp.secondaryValue : 1e6))")
                lines.append("* \(name) wattmeter: P = V(PC+,PC-) x I(CC)")

            case .functionGenerator:
                let freq = comp.secondaryValue > 0 ? comp.secondaryValue : 1000
                let period = 1.0 / freq
                switch GeneratorWaveform(rawValue: comp.modeIndex) ?? .sine {
                case .sine:
                    lines.append("\(name) \(node(0)) \(node(1)) SIN(0 \(comp.value) \(freq))")
                case .square:
                    lines.append("\(name) \(node(0)) \(node(1)) PULSE(0 \(comp.value) 0 1n 1n \(period * 0.5) \(period))")
                case .triangle:
                    lines.append("\(name) \(node(0)) \(node(1)) TRI(0 \(comp.value) \(period))")
                }

            case .schottkyDiode:
                lines.append("\(name) \(node(0)) \(node(1)) DSCHOTTKY")
                modelsToInclude.insert(".model DSCHOTTKY D (Is=1e-9 Rs=0.05 N=1.02)")

            case .probe:
                lines.append("* \(name) voltage probe on \(node(0))")

            case .opAmp, .logicAND, .logicOR, .logicNOT, .logicNAND, .logicNOR, .logicXOR, .logicXNOR, .logicBuffer:
                lines.append("* \(name) (\(comp.kind.rawValue)) is simulated by the MultiSim engine; no SPICE primitive emitted")

            case .vcvs:
                let nOutP = n.count > 0 ? n[0] : "0"
                let nOutM = n.count > 1 ? n[1] : "0"
                let nCtrlP = n.count > 2 ? n[2] : "0"
                let nCtrlM = n.count > 3 ? n[3] : "0"
                lines.append("\(name) \(nOutP) \(nOutM) \(nCtrlP) \(nCtrlM) \(comp.value)")

            case .vccs:
                let nOutP = n.count > 0 ? n[0] : "0"
                let nOutM = n.count > 1 ? n[1] : "0"
                let nCtrlP = n.count > 2 ? n[2] : "0"
                let nCtrlM = n.count > 3 ? n[3] : "0"
                lines.append("\(name) \(nOutP) \(nOutM) \(nCtrlP) \(nCtrlM) \(comp.value)")

            default:
                break
            }
        }

        if !modelsToInclude.isEmpty {
            lines.append("")
            lines.append("* Models")
            for model in modelsToInclude.sorted() {
                lines.append(model)
            }
        }

        lines.append("")
        lines.append("* Analysis Directives")
        lines.append(".tran 10u 10m")
        lines.append(".end")

        return lines.joined(separator: "\n")
    }

    private static func formatValue(_ val: Double) -> String {
        if val >= 1e6 {
            return String(format: "%.3gMEG", val / 1e6)
        } else if val >= 1e3 {
            return String(format: "%.3gk", val / 1e3)
        } else if val >= 1.0 {
            return String(format: "%.3g", val)
        } else if val >= 1e-3 {
            return String(format: "%.3gm", val * 1e3)
        } else if val >= 1e-6 {
            return String(format: "%.3gu", val * 1e6)
        } else if val >= 1e-9 {
            return String(format: "%.3gn", val * 1e9)
        } else if val >= 1e-12 {
            return String(format: "%.3gp", val * 1e12)
        } else {
            return "\(val)"
        }
    }
}
